/** 중계 철탑 가새(충돌 없음): 높이 셋의 띠와 서·북 면의 지그재그 */
function mastLattice() {
  const { x, z, half, top } = MAST;
  const x0 = x - half, x1 = x + half, z0 = z - half, z1 = z + half;
  const out = [];
  for (const y of [7, 13.5, 20]) {
    out.push(pipe([x0, y, z0], [x1, y, z0], 0.06, 'steel'), pipe([x1, y, z0], [x1, y, z1], 0.06, 'steel'),
      pipe([x1, y, z1], [x0, y, z1], 0.06, 'steel'), pipe([x0, y, z1], [x0, y, z0], 0.06, 'steel'));
  }
  const ys = [0.4, 7, 13.5, 20, top];
  for (let i = 0; i < ys.length - 1; i++) {
    const a = ys[i], b = ys[i + 1], flip = i % 2 === 1;
    out.push(pipe([x0, a, flip ? z1 : z0], [x0, b, flip ? z0 : z1], 0.05, 'steel'));
    out.push(pipe([flip ? x1 : x0, a, z0], [flip ? x0 : x1, b, z0], 0.05, 'steel'));
  }
  out.push(pipe([x, top + 0.2, z], [x, top + 3.4, z], 0.05, 'steel'), beacon(x, top + 3.6, z));
  return out;
}

