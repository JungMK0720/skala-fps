/** 구역 둘레에 바닥 빛 띠. 설치할 수 있는 범위를 바닥에서 바로 읽게 한다 */
function outline(s, mat, t = 0.12) {
  const x0 = s.x - s.w / 2, x1 = s.x + s.w / 2, z0 = s.z - s.d / 2, z1 = s.z + s.d / 2, y0 = s.y, y1 = s.y + 0.02;
  return [
    rect(x0, z0, x1, z0 + t, y0, y1, mat), rect(x0, z1 - t, x1, z1, y0, y1, mat),
    rect(x0, z0 + t, x0 + t, z1 - t, y0, y1, mat), rect(x1 - t, z0 + t, x1, z1 - t, y0, y1, mat)
  ];
}

/**
 * 구름 바다 위로 솟은 먼 봉우리. 동서·남북 능선(경사로 둘씩)을 십자로 겹쳐 어느 쪽에서 봐도 뾰족하다.
 * r = 밑변 반폭, top = 꼭대기 높이. 밑은 구름 아래에 묻힌다. snow면 동서 능선 꼭대기에 눈을 얹는다
 */
function peak(x, z, r, top, snow = false) {
  const y0 = CLOUD_Y - 2, h = top - y0, c = r / 4;
  const out = [
    ramp(x, y0, z - r / 2, c, h, r, '+z', 'concrete'), ramp(x, y0, z + r / 2, c, h, r, '-z', 'concrete'),
    ramp(x - r / 2, y0, z, r, h, c, '+x', 'concrete'), ramp(x + r / 2, y0, z, r, h, c, '-x', 'concrete')
  ];
  if (snow) {
    const s = r * 0.2, y = top - h * 0.2 + 0.15;
    out.push(ramp(x, y, z - s / 2, c * 1.02, h * 0.2, s, '+z', 'white'), ramp(x, y, z + s / 2, c * 1.02, h * 0.2, s, '-z', 'white'));
  }
  return out;
}

