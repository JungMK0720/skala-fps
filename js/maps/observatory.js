/** 구역 둘레에 바닥 빛 띠. 설치할 수 있는 범위를 바닥에서 바로 읽게 한다 */
function outline(s, mat, t = 0.12) {
  const x0 = s.x - s.w / 2, x1 = s.x + s.w / 2, z0 = s.z - s.d / 2, z1 = s.z + s.d / 2, y0 = s.y + 0.02, y1 = s.y + 0.04;
  return [
    rect(x0, z0, x1, z0 + t, y0, y1, mat), rect(x0, z1 - t, x1, z1, y0, y1, mat),
    rect(x0, z0 + t, x0 + t, z1 - t, y0, y1, mat), rect(x1 - t, z0 + t, x1, z1 - t, y0, y1, mat)
  ];
}

/** 태양광판 한 줄: 받침 + 남쪽으로 기운 판. cover가 true면 위에 막이를 올린다(길에 놓는 엄폐물용) */
function panelRow(x0, x1, z, { y = 0.6, rise = 1, depth = 1.7, cover = false } = {}) {
  const out = [
    rect(x0 + 0.4, z - 0.2, x1 - 0.4, z + 0.2, 0, y, 'steel'),
    ramp((x0 + x1) / 2, y, z, x1 - x0, rise, depth, '-z', 'tile')
  ];
  if (cover) out.push(lid(x0, z - depth / 2, x1, z + depth / 2, y + rise));
  return out;
}

/** 천막: 맞댄 경사면 둘. 올라서지 못하게 덮는다 */
function tent(x0, x1, z0, z1, top = 1.8) {
  const xm = (x0 + x1) / 2, zm = (z0 + z1) / 2, half = (x1 - x0) / 2;
  return [
    ramp((x0 + xm) / 2, 0, zm, half, top, z1 - z0, '+x', 'paper'),
    ramp((xm + x1) / 2, 0, zm, half, top, z1 - z0, '-x', 'paper'),
    lid(x0, z0, x1, z1, 0)
  ];
}

/** 맵 밖 모래 언덕: 마루를 사이에 두고 맞댄 경사면 둘. axis 'x'면 마루가 동서로 뻗는다 */
function dune(x, z, len, half, top, axis = 'x') {
  return axis === 'x'
    ? [ramp(x, 0, z - half / 2, len, top, half, '+z', 'sand'), ramp(x, 0, z + half / 2, len, top, half, '-z', 'sand')]
    : [ramp(x - half / 2, 0, z, half, top, len, '+x', 'sand'), ramp(x + half / 2, 0, z, half, top, len, '-x', 'sand')];
}

