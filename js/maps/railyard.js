/** 벽에 단 등: 받침대 + 발광 구(진짜 조명은 앞의 넷뿐이다) */
function wallLamp(x, y, z, face, color = '#ffe9c4') {
  const nx = face === '+x' ? 1 : face === '-x' ? -1 : 0, nz = face === '+z' ? 1 : face === '-z' ? -1 : 0;
  return [
    pipe([x, y + 0.25, z], [x + nx * 0.55, y + 0.25, z + nz * 0.55], 0.03),
    { type: 'light', x: x + nx * 0.55, y, z: z + nz * 0.55, color, intensity: 0.8, dist: 10 }
  ];
}

/** 건널목 경보기(충돌 없음): 기둥, 가위표, 빨간 등 둘, 올라간 차단봉. toward = 차단봉이 눕는 쪽(+1이면 +z) */
function crossingSignal(x, z, toward) {
  return [
    pipe([x, 0, z], [x, 3.6, z], 0.06, 'white'),
    pipe([x, 2.8, z - 0.55], [x, 3.6, z + 0.55], 0.045, 'white'),
    pipe([x, 3.6, z - 0.55], [x, 2.8, z + 0.55], 0.045, 'white'),
    lamp(x, 2.3, z - 0.32, RED), lamp(x, 2.3, z + 0.32, RED),
    pipe([x, 1.05, z], [x, 3.1, z + toward * 1.3], 0.05, 'white'),
    pipe([x, 3.1, z + toward * 1.3], [x, 4.5, z + toward * 2.2], 0.05, 'container_red')
  ];
}

/** 신호기 기둥(충돌 없음): 기둥, 사다리 대신 가로대, 신호등 */
function signalMast(x, z, h, colors) {
  return [
    pipe([x, 0, z], [x, h, z], 0.07, 'steel'),
    pipe([x - 0.35, h - 0.9, z], [x + 0.35, h - 0.9, z], 0.04, 'steel'),
    colors.map((c, i) => lamp(x, h - 0.25 - i * 0.42, z, c, 0.15))
  ];
}

