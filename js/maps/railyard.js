/** 선로 한 줄(남북): 도상 자갈 띠, 침목 띠, 레일 둘. 수백 개의 침목 대신 긴 띠 하나로 그린다 */
function track(cx, z0, z1, railMat = 'rust', bed = true) {
  const out = [
    rect(cx - 1.15, z0, cx + 1.15, z1, 0, 0.03, 'wood_dark'),
    rect(cx - 0.77, z0, cx - 0.67, z1, 0, 0.04, railMat),
    rect(cx + 0.67, z0, cx + 0.77, z1, 0, 0.04, railMat)
  ];
  if (bed) out.unshift(rect(cx - 1.7, z0, cx + 1.7, z1, 0, 0.01, 'sand'));
  return out;
}

/**
 * 남북으로 선 화차 한 량(폭 3 m): 땅까지 막힌 하부와 차체. 밑으로 보이거나 지나가지 못한다.
 * 벽 구실을 하는 화차는 하부를 차체와 같은 폭으로 둔다. 하부를 들이면(inset) 옆 건물과의 사이에 발목 높이 틈이 생겨 길과 길이 서로 보인다
 */
function wagon(cx, z0, z1, top, mat, inset = 0) {
  return [
    rect(cx - 1.5 + inset, z0, cx + 1.5 - inset, z1, 0, 0.9, 'metal_dark'),
    rect(cx - 1.5, z0, cx + 1.5, z1, 0.9, top, mat)
  ];
}

/** 이어진 두 화차 사이: 연결기와 통로 덮개. 차체보다 좁지만 틈 없이 막는다 */
const coupling = (cx, z0, z1, top = 3.4) => rect(cx - 0.9, z0, cx + 0.9, z1, 0, top, 'metal_dark');

/** 구역 둘레에 바닥 빛 띠. 설치할 수 있는 범위를 바닥에서 바로 읽게 한다 */
function outline(s, mat, t = 0.12) {
  const x0 = s.x - s.w / 2, x1 = s.x + s.w / 2, z0 = s.z - s.d / 2, z1 = s.z + s.d / 2, y0 = PAVE, y1 = 0.034;
  return [
    rect(x0, z0, x1, z0 + t, y0, y1, mat), rect(x0, z1 - t, x1, z1, y0, y1, mat),
    rect(x0, z0 + t, x0 + t, z1 - t, y0, y1, mat), rect(x1 - t, z0 + t, x1, z1 - t, y0, y1, mat)
  ];
}

/**
 * 계전기함·단말함 한 줄과 긴 면의 빛 띠. 빛 띠 턱이나 윗면에 서지 못하게 막이로 덮는다.
 * walled = 작은 좌표 쪽 긴 면이 벽에 붙어 있다(그쪽 빛 띠는 달지 않는다)
 */
function rackRow(x0, z0, x1, z1, neon, walled = false) {
  const alongX = x1 - x0 > z1 - z0, y0 = RACK - 0.4, y1 = RACK - 0.32;
  const out = [
    rect(x0, z0, x1, z1, 0, RACK, 'metal_dark'),
    alongX ? rect(x0, z1, x1, z1 + 0.04, y0, y1, neon) : rect(x1, z0, x1 + 0.04, z1, y0, y1, neon),
    alongX ? lid(x0, z0 - 0.06, x1, z1 + 0.06, y0) : lid(x0 - 0.06, z0, x1 + 0.06, z1, y0)
  ];
  if (!walled) out.push(alongX ? rect(x0, z0 - 0.04, x1, z0, y0, y1, neon) : rect(x0 - 0.04, z0, x0, z1, y0, y1, neon));
  return out;
}

