const C = (x, z, y, r, h, mat) => ({ type: 'cyl', x, y, z, r, h, mat });
const P = (from, to, r, mat = 'pipe') => ({ type: 'pipe', from, to, r, mat });
const SG = (x, y, z, rotY, w, h, text, bg = '#0b2545', fg = '#ffffff') => ({ type: 'sign', x, y, z, rotY, w, h, text, bg, fg });
const L = (x, y, z, color, intensity, dist) => ({ type: 'light', x, y, z, color, intensity, dist });

// 대칭 변환 (sx, sz = ±1): 박스/경사로/원통/파이프/표지판 모두 처리
const DIRS = { '+x': [1, 0], '-x': [-1, 0], '+z': [0, 1], '-z': [0, -1] };
const xf = (o, sx, sz) => {
  const c = { ...o };
  if (typeof c.x === 'number') c.x = n(c.x * sx);
  if (typeof c.z === 'number') c.z = n(c.z * sz);
  if (c.dir) {
    const [dx, dz] = DIRS[c.dir];
    c.dir = dx ? (dx * sx > 0 ? '+x' : '-x') : (dz * sz > 0 ? '+z' : '-z');
  }
  if (c.from) c.from = [n(c.from[0] * sx), c.from[1], n(c.from[2] * sz)];
  if (c.to) c.to = [n(c.to[0] * sx), c.to[1], n(c.to[2] * sz)];
  if (c.type === 'sign') c.rotY = n(Math.atan2(sx * Math.sin(o.rotY), sz * Math.cos(o.rotY)));
  return c;
};
